#!/bin/sh
# cw-sign-keys.sh - release signing keys for CleanWRT images.
#
# OpenWrt's own release process signs sysupgrade images with a usign ed25519
# keypair: the buildroot picks up `key-build` (private), `key-build.pub` and
# `key-build.ucert` from the tree root and fwtool embeds the signature into
# every generated image; sysupgrade then verifies it. This script manages
# that key material so the release pipeline can do the same.
#
# Usage:
#   tools/cw-sign-keys.sh --generate <openwrt-tree>   # create keys-release/ once
#   tools/cw-sign-keys.sh --install  <openwrt-tree>   # stage keys for `make`
#   tools/cw-sign-keys.sh --show-pub                  # print the public key
#
# Key custody (industry practice):
#   - keys-release/key-build      = PRIVATE. NEVER commit, NEVER publish. Back it
#     up offline; if it leaks, rotate (new keypair + signed announcement).
#   - key-build.pub               = publish with every release + in the repo docs.
#   - Generate ONCE per release channel; every release verifies against it.
set -eu

REPO="$(cd "$(dirname "$0")/.." && pwd)"
KEYDIR="$REPO/keys-release"
TREE="${2:-}"

# usign comes with the OpenWrt build tree (built into staging_dir/host/bin).
find_usign() {
    if [ -x "$TREE/staging_dir/host/bin/usign" ]; then
        echo "$TREE/staging_dir/host/bin/usign"
    elif command -v usign >/dev/null 2>&1; then
        command -v usign
    else
        echo "ERROR: usign not found - build the OpenWrt tree once (staging_dir/host/bin/usign) or install usign" >&2
        return 1
    fi
}

case "${1:-}" in
    --generate)
        [ -n "$TREE" ] || { echo "usage: $0 --generate <openwrt-tree>" >&2; exit 2; }
        USIGN=$(find_usign)
        [ -d "$KEYDIR" ] && [ -f "$KEYDIR/key-build" ] && { echo "keys already exist in $KEYDIR - refusing to overwrite (rotate deliberately instead)" >&2; exit 1; }
        mkdir -p "$KEYDIR"
        "$USIGN" -G -p "$KEYDIR/key-build.pub" -s "$KEYDIR/key-build"
        chmod 600 "$KEYDIR/key-build"
        echo "keypair generated in $KEYDIR"
        echo "NOTE: key-build.ucert is generated BY THE BUILDROOT on the first"
        echo "signed build (ucert -I; expires after 365 days) - copy it back to"
        echo "keys-release/ after that build and archive it with the key."
        echo "PUBLIC KEY:"
        echo "→ publish the public key with every release and in the README (private key-build stays offline)"
        ;;
    --install)
        [ -n "$TREE" ] || { echo "usage: $0 --install <openwrt-tree>" >&2; exit 2; }
        [ -f "$KEYDIR/key-build" ] || { echo "ERROR: $KEYDIR/key-build missing - run --generate first" >&2; exit 1; }
        install -m 600 "$KEYDIR/key-build"     "$TREE/key-build"
        cp "$KEYDIR/key-build.pub"  "$TREE/key-build.pub"
        # key-build.ucert: NOT staged - the buildroot generates it on the first
        # signed build (a raw pubkey copy is not a valid ucert container and
        # makes the image recipe fail). Copy the generated one back into
        # keys-release/ afterwards; it expires after 365 days.
        echo "keys staged at $TREE - make will now sign every generated image"
        ;;
    --show-pub)
        tail -1 "$KEYDIR/key-build.pub"
        ;;
    *)
        echo "usage: $0 --generate|--install|--show-pub <openwrt-tree>" >&2
        exit 2
        ;;
esac
